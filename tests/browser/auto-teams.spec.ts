import { test, expect } from '@playwright/test';

test('automatic team benefits choose a count, survive reload and publish the chosen teams offline', async ({ page, context }) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.locator('#mobile-panel').click();
  await expect(page.locator('.control-row').first()).toBeVisible();
  const state = await (await page.request.get('/api/maps/szu-1')).json();
  const controls = state.controls.filter((c: any) => (c.role ?? 'control') === 'control' && c.state !== 'rejected').slice(0, 3);
  expect(controls.some((c: any) => c.servicePerPersonSec > 0)).toBe(true);
  const ids = controls.map((c: any) => c.id);
  const boxes = page.locator('[data-required]');
  for (let i = 0; i < await boxes.count(); i++) {
    const box = boxes.nth(i);
    if (!await box.isDisabled()) await box.setChecked(ids.includes(await box.getAttribute('data-required')));
  }
  await page.locator('#people').fill('12');
  await page.locator('#stagger').fill('0');
  await page.locator('.auto-team-settings summary').click();
  await page.locator('#auto-min-people').fill('2');
  await page.locator('#auto-max-teams').fill('6');
  await page.locator('#auto-gain').fill('90');
  const submission = page.waitForResponse(r => r.url().endsWith('/api/plans/auto-teams') && r.request().method() === 'POST');
  await page.locator('#recommend-teams').click();
  const job = await (await submission).json();
  await expect(page.locator('.team-recommendation')).toContainText('自动建议 4 队', { timeout: 30000 });
  await expect(page.locator('.route-card')).toHaveCount(4);
  await expect(page.locator('#teams')).toHaveValue('4');
  await page.locator('.team-comparison summary').click();
  await expect(page.locator('[data-comparison-count]')).toHaveCount(6);
  await expect(page.locator('[data-comparison-count="4"]')).toHaveClass(/recommended/);
  const plan = (await (await page.request.get('/api/jobs/'+job.id)).json()).result;
  expect(plan.teamRecommendation.allCountsCompared).toBe(true);
  expect(plan.request.teams.map((t: any) => t.people)).toEqual([3, 3, 3, 3]);
  const chosen = plan.teamRecommendation.candidates.find((c: any) => c.recommended);
  expect(chosen.totalDistanceM).toBeCloseTo(plan.routes.reduce((n: number, r: any) => n+r.distanceM, 0), 5);
  expect(chosen.latestFinishSec).toBeCloseTo(Math.max(...plan.routes.map((r: any) => r.finishSec)), 5);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '/tmp/dirmap-auto-team-phone.png' });
  await page.reload(); await page.locator('#mobile-panel').click();
  await page.locator('.auto-team-settings summary').click();
  await expect(page.locator('#teams')).toHaveValue('4');
  await expect(page.locator('#auto-max-teams')).toHaveValue('6');
  await expect(page.locator('#auto-gain')).toHaveValue('90');
  await page.locator('.job-history summary').click();
  await page.locator(`[data-resume-job="${job.id}"]`).click();
  await expect(page.locator('.route-card')).toHaveCount(4, { timeout: 30000 });
  await page.locator('#review-button').click();
  for (const name of ['registration', 'controls', 'passages']) await page.locator('#review-'+name).check();
  if (await page.locator('#review-approaches').count()) await page.locator('#review-approaches').check();
  await page.locator('#publish-confirm').click();
  const link = page.getByLabel('学生课程链接');
  await expect(link).toBeVisible({ timeout: 30000 });
  const courseId = new URL(await link.inputValue()).searchParams.get('course');
  const course = await (await page.request.get('/api/releases/'+courseId)).json();
  expect(course.plan.teamRecommendation.recommendedCount).toBe(4);
  expect(course.plan.request.version).toBe(course.version);
  expect(course.plan.routes).toHaveLength(4);
  await page.goto(`http://127.0.0.1:8768/?course=${courseId}`, { waitUntil: 'domcontentloaded' });
  await expect(page.locator('#offline-status')).toContainText('本课已保存', { timeout: 20000 });
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await context.setOffline(true); await page.reload();
  await page.locator('#mobile-panel').click();
  await expect(page.locator('#student-team option')).toHaveCount(4);
  await expect(page.locator('#student-overview')).toContainText('3 人同行');
  await page.locator('#check-in').click();
  await expect(page.locator('#student-progress')).toHaveText('1 / 3');
  await context.setOffline(false);
});

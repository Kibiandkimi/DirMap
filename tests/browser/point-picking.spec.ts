import { test, expect } from './fixtures';

test('original and standard map picks can be zoomed, adjusted and cancelled before confirmation', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('.control-row', { state: 'attached' });
  await page.locator('#mobile-panel').click();
  await page.locator('[data-tab="registration"]').click();
  await page.locator('#add-anchor').click();
  const viewport = page.locator('.editor-viewport'), canvas = page.locator('dialog canvas');
  await expect(canvas).toBeVisible();
  await expect(page.locator('#confirm-point')).toBeDisabled();
  const box = (await viewport.boundingBox())!, center = { x: box.x + box.width / 2, y: box.y + box.height / 2 };
  await page.mouse.move(center.x, center.y); await page.mouse.down();
  await page.mouse.move(center.x + 30, center.y + 35, { steps: 6 }); await page.mouse.up();
  await expect(page.locator('#confirm-point')).toBeDisabled();
  const beforeWheel = (await canvas.boundingBox())!.width;
  await page.mouse.move(center.x, center.y); await page.mouse.wheel(0, -260);
  await expect.poll(async () => (await canvas.boundingBox())!.width).toBeGreaterThan(beforeWheel * 1.3);
  // Real touch input, including the release of two fingers, must not choose.
  const cdp = await context.newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 2 });
  const beforePinch = (await canvas.boundingBox())!.width;
  const touches = (spread: number) => [{ x: center.x - spread, y: center.y, id: 0 }, { x: center.x + spread, y: center.y, id: 1 }];
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: touches(24) });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: touches(54) });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await expect.poll(async () => (await canvas.boundingBox())!.width).toBeGreaterThan(beforePinch * 1.5);
  await expect(page.locator('#confirm-point')).toBeDisabled();
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: false });
  await page.mouse.click(center.x, center.y);
  await expect(page.locator('dialog')).toBeVisible();
  await expect(page.locator('#confirm-point')).toBeEnabled();
  const first = await page.locator('#point-preview').innerText();
  await page.mouse.click(center.x + 26, center.y - 18);
  await expect(page.locator('#point-preview')).not.toHaveText(first);
  await page.locator('#cancel-point').click();
  await expect(page.locator('#confirm-point')).toBeDisabled();
  await page.mouse.click(center.x + 10, center.y + 10);
  await page.locator('#confirm-point').click();
  await expect(page.locator('dialog')).toHaveCount(0);
  await expect(page.locator('#map-action-hint')).toContainText('同一建筑角或路口');
  await expect(page.locator('#confirm-map-point')).toBeDisabled();
  const pick = (point: number[]) => page.evaluate(point => (window as any).dirmap.campusMap.onClick(point, null), point);
  const anchorCount = () => page.evaluate(() => (window as any).dirmap.campusMap.anchorPoints.getFeatures().length);
  await pick([113.9304, 22.535]);
  expect(await anchorCount()).toBe(0);
  await expect(page.locator('#map-pick-position')).toContainText('22.535000');
  await pick([113.931, 22.536]);
  await expect(page.locator('#map-pick-position')).toContainText('22.536000');
  await page.screenshot({ path: '/tmp/dirmap-map-point-confirmation.png' });
  await page.locator('#confirm-map-point').click();
  expect(await anchorCount()).toBe(1);
  await expect(page.locator('#map-action-hint')).toBeHidden();
  await page.locator('#mobile-panel').click();
  await expect(page.locator('#anchor-list')).toContainText('113.931000, 22.536000');
  await page.locator('[data-remove-anchor]').click(); expect(await anchorCount()).toBe(0);
});

test('new checkpoints remain a single preview, and changing start or finish does not commit on tap', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await expect(page.locator('.control-row').first()).toBeVisible();
  await page.locator('#edit-controls').click();
  await page.locator('#edit-mode').selectOption('control');
  const box = (await page.locator('.editor-viewport').boundingBox())!;
  await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
  await expect(page.locator('#control-label')).toHaveCount(0);
  await expect(page.locator('#save-edits')).toBeDisabled();
  await page.mouse.click(box.x + box.width / 2 + 20, box.y + box.height / 2 + 15);
  await page.locator('#confirm-point').click();
  await expect(page.locator('#control-label')).toHaveValue(/新点/);
  await expect(page.locator('#save-edits')).toBeEnabled();
  await page.locator('#undo-edit').click();
  await expect(page.locator('#control-label')).toHaveCount(0);
  await page.locator('[data-close]').click();
  const state = await (await page.request.get('/api/maps/szu-1')).json();
  const target = state.controls.find((c: any) => c.lnglat && c.calibrated && (c.role ?? 'control') === 'control').lnglat;
  const endpoints = () => page.evaluate(() => (window as any).dirmap.campusMap.endpoints.getFeatures().map((f: any) => [f.getId(), f.getGeometry().getCoordinates()]));
  const previous = await endpoints();
  await page.locator('#pick-start').click();
  await page.evaluate(p => (window as any).dirmap.campusMap.onClick(p, null), target);
  expect(await endpoints()).toEqual(previous);
  await page.locator('#cancel-map-point').click(); expect(await endpoints()).toEqual(previous);
  await page.locator('#pick-start').click();
  await page.evaluate(() => (window as any).dirmap.campusMap.onClick([0, 0], null));
  await expect(page.locator('#confirm-map-point')).toBeDisabled();
  await expect(page.locator('#map-pick-position')).toContainText('超出已校准范围');
  await page.evaluate(p => (window as any).dirmap.campusMap.onClick(p, null), target);
  await page.locator('#confirm-map-point').click();
  const changed = await endpoints(); expect(changed).not.toEqual(previous);
  expect(changed.find((p: any) => p[0] === 'start')[1]).toEqual(changed.find((p: any) => p[0] === 'finish')[1]);
  await page.locator('#pick-finish').click();
  await page.evaluate(p => (window as any).dirmap.campusMap.onClick(p, null), target);
  await page.keyboard.press('Escape'); expect(await endpoints()).toEqual(changed);
  await expect(page.locator('#map-action-hint')).toBeHidden();
});

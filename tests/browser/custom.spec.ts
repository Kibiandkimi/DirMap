import { test, expect } from '@playwright/test';

test('phone custom routes retain each team order, report gathering waits and survive reload/publication', async ({ page, context }) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.locator('#mobile-panel').click();
  await expect(page.locator('.control-row').first()).toBeVisible();
  const state = await (await page.request.get('/api/maps/szu-1')).json();
  const controls = state.controls.filter((c: any) => (c.role ?? 'control') === 'control');
  const chosen = controls.slice(0, 3), ids = chosen.map((c: any) => c.id);
  const boxes = page.locator('[data-required]');
  for (let i = 0; i < await boxes.count(); i++) {
    const box = boxes.nth(i);
    if (!(await box.isDisabled())) await box.setChecked(ids.includes(await box.getAttribute('data-required')));
  }
  await page.locator('#people').fill('6'); await page.locator('#teams').fill('2');
  await page.locator('#stagger').fill('600');
  await page.locator('#course-mode').selectOption('custom');
  await page.locator(`[data-mandatory="${ids[0]}"]`).check();
  await page.locator(`[data-mandatory="${ids[1]}"]`).check();
  await page.locator('#mandatory-order').check();
  const first = `${chosen[0].label} → ${chosen[2].label} → ${chosen[1].label}`;
  const second = `${chosen[0].label}，${chosen[1].label}`;
  await page.locator('#custom-team-0').fill(first);
  await page.locator('[data-team-index="1"] summary').click();
  await page.locator('#custom-team-1').fill(`${chosen[1].label} ${chosen[0].label}`);
  await page.locator('#plan-button').click();
  await expect(page.locator('#custom-route-error')).toContainText('顺序');
  await page.locator('#custom-team-1').fill(second);
  await page.reload(); await page.locator('#mobile-panel').click();
  await expect(page.locator('#course-mode')).toHaveValue('custom');
  await expect(page.locator('#teams')).toHaveValue('2');
  await expect(page.locator('#custom-team-0')).toHaveValue(first);
  await expect(page.locator('#custom-team-1')).toHaveValue(second);
  const submitted = page.waitForResponse(r => r.url().endsWith('/api/plans') && r.request().method() === 'POST');
  await page.locator('#plan-button').click();
  const job = await (await submitted).json();
  await expect(page.locator('.route-card')).toHaveCount(2, { timeout: 30000 });
  await expect(page.locator('#route-results')).toContainText('按自定义点序');
  const result = (await (await page.request.get('/api/jobs/' + job.id)).json()).result;
  expect(result.status).toBe('FIXED');
  expect(result.routes.map((r: any) => r.controlIds)).toEqual([[ids[0], ids[2], ids[1]], [ids[0], ids[1]]]);
  expect(result.routes[0].waitSec).toBeGreaterThan(500);
  expect(result.rendezvous).toHaveLength(2);
  for (const meeting of result.rendezvous) {
    const stops = result.routes.map((r: any) => r.stops.find((s: any) => s.controlId === meeting.controlId));
    expect(stops[0].departureSec).toBe(stops[1].departureSec);
    expect(meeting.departureSec).toBe(Math.max(...stops.map((s: any) => s.readySec)));
  }
  await page.locator('.meeting-schedule summary').click();
  await expect(page.locator('.meeting-schedule tbody tr')).toHaveCount(4);
  await page.locator('#review-button').click();
  for (const name of ['registration', 'controls', 'passages']) await page.locator('#review-' + name).check();
  if (await page.locator('#review-approaches').count()) await page.locator('#review-approaches').check();
  await page.locator('#publish-confirm').click();
  const link = page.getByLabel('学生课程链接');
  await expect(link).toBeVisible({ timeout: 30000 });
  const id = new URL(await link.inputValue()).searchParams.get('course');
  const course = await (await page.request.get('/api/releases/' + id)).json();
  expect(course.plan.request.customRoutes).toEqual(result.request.customRoutes);
  expect(course.plan.routes.map((r: any) => r.controlIds)).toEqual(result.routes.map((r: any) => r.controlIds));
  expect(course.plan.rendezvous).toHaveLength(2);
  await page.goto(`http://127.0.0.1:8768/?course=${id}`, { waitUntil: 'domcontentloaded' });
  await expect(page.locator('#offline-status')).toContainText('本课已保存', { timeout: 20000 });
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await page.locator('#mobile-panel').click();
  await page.locator('#check-in').click();
  await expect(page.locator('#next-control')).toContainText('等待全班集合');
  await expect(page.locator('#check-in')).toBeDisabled();
  await context.setOffline(true); await page.reload();
  await page.locator('#mobile-panel').click();
  await expect(page.locator('#next-control')).toContainText('等待全班集合');
  await page.locator('#meeting-departure').click();
  await expect(page.locator('#next-control .next-label')).toHaveText(`目标 ${chosen[2].label}`);
  await page.reload(); await page.locator('#mobile-panel').click();
  await expect(page.locator('#next-control .next-label')).toHaveText(`目标 ${chosen[2].label}`);
  await context.setOffline(false);
});

import { test, expect } from './fixtures';

test('continue the chosen real-map team count, recover during computation, and publish exact refined routes offline', async ({ page, context }) => {
  test.setTimeout(180000);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.locator('#mobile-panel').click();
  await page.locator('[data-map="szu-3"]').click();
  await expect(page.locator('#course-mode')).toHaveValue('mixed_coverage');
  const boxes = page.locator('[data-required]');
  for (let i = 0; i < await boxes.count(); i++) {
    if (!await boxes.nth(i).isDisabled()) await boxes.nth(i).check();
  }
  await page.locator('#people').fill('20'); await page.locator('#stagger').fill('0');
  await page.locator('.auto-team-settings summary').click();
  await page.locator('#auto-min-people').fill('2'); await page.locator('#auto-max-teams').fill('10');
  await page.locator('#recommend-teams').click();
  await expect(page.locator('.team-recommendation')).toContainText('自动建议 4 队', { timeout: 30000 });
  await page.locator('.team-comparison summary').click();
  const chosenResponse = page.waitForResponse(r => r.url().endsWith('/api/plans/choose-team-count') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '采用 6 队', exact: true }).click();
  const chosenJob = await (await chosenResponse).json();
  await expect(page.locator('.route-card')).toHaveCount(6, { timeout: 30000 });
  const chosen = (await (await page.request.get('/api/jobs/'+chosenJob.id)).json()).result;
  await page.locator('#solver-budget').selectOption('30');
  await expect(page.locator('.route-card')).toHaveCount(6);
  await expect(page.locator('#refine-plan')).toBeEnabled();
  let submissions = 0;
  page.on('request', request => { if (request.url().endsWith('/api/plans/refine') && request.method() === 'POST') submissions++; });
  const refinedResponse = page.waitForResponse(r => r.url().endsWith('/api/plans/refine') && r.request().method() === 'POST');
  await page.locator('#refine-plan').click();
  const response = await refinedResponse;
  expect(response.request().postDataJSON()).toMatchObject({ planId: chosen.id, timeLimitSec: 30 });
  const refinedJob = await response.json();
  await expect(page.locator('.route-card')).toHaveCount(6);
  await expect(page.locator('#review-button')).toBeDisabled();
  await page.reload(); await page.locator('#mobile-panel').click();
  await page.locator('.job-history summary').click();
  await page.locator(`[data-resume-job="${refinedJob.id}"]`).click();
  await expect(page.locator('.refinement-card')).toContainText(/本轮路线已改善|保留原有路线/, { timeout: 60000 });
  expect(submissions).toBe(1);
  const refined = (await (await page.request.get('/api/jobs/'+refinedJob.id)).json()).result;
  expect(refined.refinement.sourcePlanId).toBe(chosen.id);
  expect(refined.refinement.round).toBe(1);
  expect(refined.request.teams).toEqual(chosen.request.teams);
  expect(refined.teamRecommendation.selectedCount).toBe(6);
  expect(refined.teamRecommendation.refinedCounts).toEqual([6]);
  const before = refined.refinement.before, after = refined.refinement.after;
  expect(after.latestFinishSec).toBeLessThanOrEqual(before.latestFinishSec+1e-7);
  if (Math.abs(after.latestFinishSec-before.latestFinishSec) < 1e-7) expect(after.totalFinishSec).toBeLessThanOrEqual(before.totalFinishSec+1e-7);
  if (!refined.refinement.improved) expect(refined.routes.map((r: any) => r.geometry)).toEqual(chosen.routes.map((r: any) => r.geometry));
  await expect(page.locator('#teams')).toHaveValue('6');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('.refinement-card').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/dirmap-refinement-phone.png' });
  await page.locator('#review-button').click();
  for (const name of ['registration', 'controls', 'passages']) await page.locator('#review-'+name).check();
  if (await page.locator('#review-approaches').count()) await page.locator('#review-approaches').check();
  const confirmation = page.waitForResponse(r => r.url().endsWith('/api/plans/confirm') && r.request().method() === 'POST');
  await page.locator('#publish-confirm').click();
  expect((await confirmation).request().postDataJSON().planId).toBe(refined.id);
  const link = page.getByLabel('学生课程链接');
  await expect(link).toBeVisible({ timeout: 30000 });
  const courseId = new URL(await link.inputValue()).searchParams.get('course');
  const course = await (await page.request.get('/api/releases/'+courseId)).json();
  expect(course.plan.routes.map((r: any) => r.geometry)).toEqual(refined.routes.map((r: any) => r.geometry));
  expect(course.plan.routes.map((r: any) => r.controlIds)).toEqual(refined.routes.map((r: any) => r.controlIds));
  expect(course.plan.refinement).toEqual(refined.refinement);
  expect(course.plan.teamRecommendation.selectedCount).toBe(6);
  await page.goto(`http://127.0.0.1:8768/?course=${courseId}`, { waitUntil: 'domcontentloaded' });
  await expect(page.locator('#offline-status')).toContainText('本课已保存', { timeout: 20000 });
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await context.setOffline(true); await page.reload();
  await page.locator('#mobile-panel').click();
  await expect(page.locator('#student-team option')).toHaveCount(6);
  await context.setOffline(false);
});
